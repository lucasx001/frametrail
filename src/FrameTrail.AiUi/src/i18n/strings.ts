export function t(
  strings: Record<string, string>,
  locale: LocaleCode,
  key: string,
  ...args: Array<string | number>
): string {
  const fallback = FALLBACK_STRINGS[locale] ?? FALLBACK_STRINGS['zh-Hans'];
  let template = strings[key] ?? fallback[key] ?? key;

  args.forEach((arg, idx) => {
    const formatted =
      typeof arg === 'number'
        ? template.includes(`{${idx}:0.0}`)
          ? arg.toFixed(1)
          : String(arg)
        : String(arg);
    template = template.replace(`{${idx}:0.0}`, formatted).replace(`{${idx}}`, formatted);
  });

  return template;
}
